/* OGCODE shop — shared cart for Metachess, Chess sets and the Cart page.
   Products and prices come from the shop-data block (generated by the build).
   The real price check happens on the server in api/checkout.js (Viva.com). */
(function(){
  var dataEl = document.getElementById('shop-data'); if(!dataEl) return;
  var CAT = JSON.parse(dataEl.textContent);
  var fmt = new Intl.NumberFormat('en-IE',{style:'currency',currency:CAT.currency});
  var money = function(c){ return fmt.format(c/100); };
  var $ = function(s){ return document.querySelector(s); };
  var KEY = 'ogcode-cart';
  var cart = {};
  try { cart = JSON.parse(localStorage.getItem(KEY) || '{}') || {}; } catch(e){ cart = {}; }
  var byId = {}; CAT.products.forEach(function(p){ byId[p.id] = p; });
  Object.keys(cart).forEach(function(id){ if(!byId[id] || !(cart[id] > 0)) delete cart[id]; });
  function save(){ try { localStorage.setItem(KEY, JSON.stringify(cart)); } catch(e){} }
  function totals(){ var n = 0, sub = 0; Object.keys(cart).forEach(function(id){ n += cart[id]; sub += byId[id].price * cart[id]; }); return {n:n, sub:sub}; }

  // ---- add to cart (product pages) ----
  document.addEventListener('click', function(e){
    var b = e.target.closest('[data-add],[data-add-select]'); if(!b) return;
    var sel = b.hasAttribute('data-add-select') ? b.closest('.prod').querySelector('select') : null;
    var id = sel ? sel.value : b.getAttribute('data-add');
    if(!byId[id]) return;
    cart[id] = Math.min(10, (cart[id] || 0) + 1); save(); render();
    b.textContent = 'Added ✓'; setTimeout(function(){ b.textContent = 'Add to cart'; }, 1200);
  });

  // Metachess cards: material picker updates the price and shows the matching render
  document.querySelectorAll('.prod select.mc-mat').forEach(function(sel){
    var card = sel.closest('.prod'), price = card.querySelector('.prod-price'), track = card.querySelector('.track');
    sel.addEventListener('change', function(){
      var o = sel.selectedOptions[0];
      price.textContent = money(+o.getAttribute('data-price'));
      var i = (+o.getAttribute('data-img') || 1) - 1;
      if(track) track.scrollTo({left: i * track.clientWidth, behavior: 'smooth'});
    });
  });

  // ---- cart page ----
  var list = $('#cart-items'), regionSel = $('#cart-region');
  if(regionSel){
    regionSel.innerHTML = CAT.shipping.map(function(r){ return '<option value="'+r.id+'">'+r.label+' · '+money(r.amount)+'</option>'; }).join('');
    try { var savedRegion = localStorage.getItem(KEY+'-region'); if(savedRegion) regionSel.value = savedRegion; } catch(e){}
    regionSel.addEventListener('change', function(){ try { localStorage.setItem(KEY+'-region', regionSel.value); } catch(e){} fillCountries(); render(); });
  }
  var form = $('#cart-form'), countrySel = $('#c-country');
  var names = null; try { names = new Intl.DisplayNames(['en'], {type:'region'}); } catch(e){}
  function fillCountries(){
    if(!countrySel || !regionSel) return;
    var region = CAT.shipping.filter(function(r){ return r.id === regionSel.value; })[0] || CAT.shipping[0];
    var keep = countrySel.value;
    var opts = region.countries.map(function(c){ return {c:c, n: names ? names.of(c) : c}; })
      .sort(function(a,b){ return a.n.localeCompare(b.n); });
    countrySel.innerHTML = opts.map(function(o){ return '<option value="'+o.c+'">'+o.n+'</option>'; }).join('');
    if(region.countries.indexOf(keep) > -1) countrySel.value = keep;
    else if(region.countries.indexOf('GR') > -1) countrySel.value = 'GR';
  }
  fillCountries();
  if(form) form.addEventListener('input', function(){ var s = $('#cart-status'); if(s && s.dataset.form){ s.textContent = ''; s.className = 'status'; delete s.dataset.form; } render(); });

  // back from Viva without paying (the failure address is this page, with ?s=<order code>)
  var back = new URLSearchParams(location.search);
  if(back.get('s') && $('#cart-status')){
    var st = $('#cart-status'), code = back.get('s'), tx = back.get('t') || '';
    st.className = 'status'; st.textContent = 'Checking your payment…';
    try { history.replaceState(null, '', location.pathname); } catch(e){}
    fetch('/api/payment-status?s=' + encodeURIComponent(code) + (tx ? '&t=' + encodeURIComponent(tx) : ''))
      .then(function(r){ return r.json(); }).catch(function(){ return {}; })
      .then(function(j){
        if(j.status === 'paid' || j.status === 'pending'){ location.replace('shop-success.html?s=' + encodeURIComponent(code) + (tx ? '&t=' + encodeURIComponent(tx) : '')); return; }
        st.className = 'status err';
        st.textContent = 'The payment did not go through, so nothing was charged. Your cart is still here: try again, or use another payment method.';
      });
  }
  if(list) list.addEventListener('click', function(e){
    var b = e.target.closest('[data-q]'); if(!b) return;
    var id = b.getAttribute('data-q'); cart[id] = (cart[id] || 0) + parseInt(b.getAttribute('data-d'), 10);
    if(cart[id] <= 0) delete cart[id]; if(cart[id] > 10) cart[id] = 10; save(); render();
  });

  function render(){
    var t = totals();
    // nav badge + floating bar on product pages
    document.querySelectorAll('a[href="shop.html"]').forEach(function(a){
      if(!a.closest('nav') || a.closest('.crumbs')) return;
      var bd = a.querySelector('.badge');
      if(t.n){ if(!bd){ bd = document.createElement('span'); bd.className = 'badge'; a.appendChild(bd); } bd.textContent = t.n; }
      else if(bd) bd.remove();
    });
    var bar = $('.cartbar');
    if(bar){ bar.hidden = !t.n; bar.querySelector('.cb-count').textContent = t.n + (t.n === 1 ? ' item' : ' items'); bar.querySelector('.cb-sub').textContent = money(t.sub); }
    if(!list) return;
    list.innerHTML = Object.keys(cart).map(function(id){
      var p = byId[id], q = cart[id];
      return '<li>'+(p.photo ? '<img class="ci-img" src="'+p.photo+'" alt="">' : '')+'<span class="ci-name">'+p.name+'</span>'+
        '<span class="stepper sm"><button type="button" data-q="'+id+'" data-d="-1" aria-label="One less '+p.name+'">−</button><input type="number" value="'+q+'" readonly aria-label="Quantity of '+p.name+'"><button type="button" data-q="'+id+'" data-d="1" aria-label="One more '+p.name+'">+</button></span>'+
        '<span class="ci-price">'+money(p.price*q)+'</span></li>';
    }).join('');
    var region = CAT.shipping.filter(function(r){ return r.id === regionSel.value; })[0] || CAT.shipping[0];
    var ship = t.n ? region.amount : 0;
    $('#cart-empty').hidden = t.n > 0;
    $('#cart-count').textContent = t.n;
    $('#cart-sub').textContent = money(t.sub);
    $('#cart-ship').textContent = t.n ? money(ship) : '—';
    $('#cart-total').textContent = money(t.sub + ship);
    var ok = $('#cart-terms'); $('#cart-go').disabled = !t.n || !(ok && ok.checked);
  }

  var terms = $('#cart-terms'); if(terms) terms.addEventListener('change', render);
  var go = $('#cart-go');
  if(go) go.addEventListener('click', function(){
    var btn = this, status = $('#cart-status');
    var items = Object.keys(cart).map(function(id){ return {id:id, qty:cart[id]}; });
    if(form && !form.checkValidity()){
      form.reportValidity();
      status.className = 'status err'; status.textContent = 'Please fill in your delivery details first.'; status.dataset.form = '1';
      return;
    }
    var customer = {};
    if(form) new FormData(form).forEach(function(v, k){ customer[k] = String(v).trim(); });
    btn.disabled = true; btn.textContent = 'Opening secure checkout…'; status.className = 'status'; status.textContent = '';
    fetch('/api/checkout', {method:'POST', headers:{'Content-Type':'application/json'}, body: JSON.stringify({items:items, region:regionSel.value, customer:customer, acceptedTerms: !!($('#cart-terms') && $('#cart-terms').checked)})})
      .then(function(r){ return r.json().catch(function(){ return {}; }).then(function(j){ if(!r.ok || !j.url) throw new Error(j.error || 'Checkout is not available right now.'); return j; }); })
      .then(function(j){ window.location.href = j.url; })
      .catch(function(err){
        status.className = 'status err';
        status.textContent = err.message + ' You can also order by email at ogcode3d@gmail.com.';
        btn.disabled = false; btn.textContent = 'Checkout';
      });
  });
  window.addEventListener('storage', function(e){ if(e.key === KEY){ try { cart = JSON.parse(e.newValue || '{}') || {}; } catch(x){} render(); } });
  render();
})();
